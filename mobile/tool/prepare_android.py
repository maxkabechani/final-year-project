from pathlib import Path
import re

manifest = Path("android/app/src/main/AndroidManifest.xml")
if not manifest.exists():
    raise SystemExit("Android manifest was not generated by flutter create")

source = manifest.read_text(encoding="utf-8")
permissions = [
    '    <uses-permission android:name="android.permission.INTERNET"/>',
    '    <uses-permission android:name="android.permission.USE_BIOMETRIC"/>',
    '    <uses-permission android:name="android.permission.BLUETOOTH_SCAN" android:usesPermissionFlags="neverForLocation"/>',
    '    <uses-permission android:name="android.permission.BLUETOOTH_CONNECT"/>',
    '    <uses-permission android:name="android.permission.BLUETOOTH" android:maxSdkVersion="30"/>',
    '    <uses-permission android:name="android.permission.BLUETOOTH_ADMIN" android:maxSdkVersion="30"/>',
    '    <uses-permission android:name="android.permission.ACCESS_FINE_LOCATION" android:maxSdkVersion="30"/>',
]
missing = [item for item in permissions if item not in source]
if missing:
    marker = "    <application"
    if marker not in source:
        raise SystemExit("Could not locate application element in Android manifest")
    source = source.replace(marker, "\n".join(missing) + "\n" + marker, 1)
    manifest.write_text(source, encoding="utf-8")

kotlin_files = list(Path("android/app/src/main/kotlin").rglob("MainActivity.kt"))
java_files = list(Path("android/app/src/main/java").rglob("MainActivity.java"))
if kotlin_files:
    activity = kotlin_files[0]
    source = activity.read_text(encoding="utf-8")
    source = source.replace(
        "import io.flutter.embedding.android.FlutterActivity",
        "import io.flutter.embedding.android.FlutterFragmentActivity",
    )
    source = re.sub(r"(:\s*)FlutterActivity(\s*\()", r"\1FlutterFragmentActivity\2", source)
    activity.write_text(source, encoding="utf-8")
elif java_files:
    activity = java_files[0]
    source = activity.read_text(encoding="utf-8")
    source = source.replace(
        "import io.flutter.embedding.android.FlutterActivity;",
        "import io.flutter.embedding.android.FlutterFragmentActivity;",
    )
    source = source.replace(
        "extends FlutterActivity",
        "extends FlutterFragmentActivity",
    )
    activity.write_text(source, encoding="utf-8")
else:
    raise SystemExit("Could not locate the generated Android MainActivity")

style_files = list(Path("android/app/src/main/res").rglob("styles.xml"))
for style_file in style_files:
    source = style_file.read_text(encoding="utf-8")
    updated = re.sub(
        r'(<style\s+name="LaunchTheme"\s+parent=")[^"]+(")',
        r"\1Theme.AppCompat.DayNight\2",
        source,
    )
    if updated != source:
        style_file.write_text(updated, encoding="utf-8")

if not style_files:
    raise SystemExit("Could not locate generated Android styles.xml")

debug_manifest = Path("android/app/src/debug/AndroidManifest.xml")
debug_manifest.parent.mkdir(parents=True, exist_ok=True)
if not debug_manifest.exists():
    debug_manifest.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<manifest xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <application android:usesCleartextTraffic="true" />\n'
        '</manifest>\n',
        encoding="utf-8",
    )
else:
    source = debug_manifest.read_text(encoding="utf-8")
    attribute = 'android:usesCleartextTraffic="true"'
    if 'android:usesCleartextTraffic=' in source:
        source = re.sub(
            r'android:usesCleartextTraffic="[^"]+"',
            attribute,
            source,
            count=1,
        )
    elif "<application" in source:
        source = source.replace("<application", "<application " + attribute, 1)
    else:
        source = source.replace(
            "</manifest>",
            "    <application " + attribute + " />\n</manifest>",
            1,
        )
    debug_manifest.write_text(source, encoding="utf-8")

kotlin_gradle = Path("android/app/build.gradle.kts")
groovy_gradle = Path("android/app/build.gradle")
if kotlin_gradle.exists():
    gradle_file = kotlin_gradle
    dependency_line = '    implementation("androidx.appcompat:appcompat:1.7.1")'
elif groovy_gradle.exists():
    gradle_file = groovy_gradle
    dependency_line = "    implementation 'androidx.appcompat:appcompat:1.7.1'"
else:
    raise SystemExit("Could not locate the generated Android app Gradle file")

source = gradle_file.read_text(encoding="utf-8")
if "androidx.appcompat:appcompat" not in source:
    marker = "dependencies {"
    if marker not in source:
        raise SystemExit("Could not locate dependencies block in Android app Gradle file")
    source = source.replace(marker, marker + "\n" + dependency_line, 1)
    gradle_file.write_text(source, encoding="utf-8")
