from pathlib import Path
import plistlib
import re

ios_dir = Path("ios")
info_plist = ios_dir / "Runner" / "Info.plist"
project_file = ios_dir / "Runner.xcodeproj" / "project.pbxproj"

if not info_plist.is_file():
    raise SystemExit("iOS Info.plist was not generated by flutter create")
with info_plist.open("rb") as source:
    info = plistlib.load(source)
info.update(
    {
        "NSBluetoothAlwaysUsageDescription": (
            "Smart Access uses Bluetooth to find nearby door controllers and "
            "request authorized access."
        ),
        "NSBluetoothPeripheralUsageDescription": (
            "Smart Access uses Bluetooth to find nearby door controllers and "
            "request authorized access."
        ),
        "NSFaceIDUsageDescription": (
            "Use Face ID to confirm your identity before requesting door access."
        ),
    }
)
with info_plist.open("wb") as destination:
    plistlib.dump(info, destination, fmt=plistlib.FMT_XML, sort_keys=False)

if not project_file.is_file():
    raise SystemExit("iOS Xcode project was not generated by flutter create")
project_source = project_file.read_text(encoding="utf-8")
project_source, replacements = re.subn(
    r"IPHONEOS_DEPLOYMENT_TARGET\\s*=\\s*[0-9.]+;",
    "IPHONEOS_DEPLOYMENT_TARGET = 13.0;",
    project_source,
)
if replacements == 0:
    raise SystemExit("Could not set the iOS deployment target to 13.0")
project_file.write_text(project_source, encoding="utf-8")
